"""The exact search with 100 000 photos, on the embedded PostgreSQL 16.

RFC-038 section 14.1 found that the installed app's search never uses the
HNSW index: on PostgreSQL 16 the tie-break on `id` turns the query into a scan
of every vector, and what that costs with a large collection was left to "the
scale benchmark". The map and browse measurements of RFC-040 and RFC-044 ran
with 100 000 rows, but with one vector repeated in all of them, which a
semantic search cannot use. This script answers the question:

1. **The rows.** 100 000 images on one device, each with its own random
   vector, L2-normalized like CLIP's, generated by the server
   (`random()`, `l2_normalize`). Random vectors cost the scan exactly what
   real ones cost -- the distance is computed for every row either way, and
   neither compresses -- and they need no model. The HNSW index is dropped
   first, as RFC-040 dropped it: on PostgreSQL 16 it never serves the search,
   and its upkeep would be the cost of the seeding.
2. **The search, as the app runs it.** `PostgresImageRepository.search_similar()`
   with no filter, `limit` 40 (the first page) and 100 (the most the API
   gives), for 25 query vectors, three rounds: the first after a restart of
   nothing, as it comes, the next two warm. And one `EXPLAIN (ANALYZE,
   BUFFERS)`, which says where the time goes.
3. **One hypothesis.** A `vector(512)` is 2 056 bytes, over the ~2 KB at
   which PostgreSQL moves a value out of the row (TOAST): every row the scan
   reads costs a second lookup, in the TOAST table, to fetch its vector. The
   same rows are copied into a table whose column is `STORAGE PLAIN`, which
   keeps the vector in the row, and the search is measured again there. This
   is a measurement, not a change: the app's table is not touched.

Run it inside `embedded run`, against a cluster of its own, never the
development one -- the rows are 300 MB, and the HNSW index is dropped:

    $env:EMBEDDED_POSTGRES_DIRECTORY = "<an empty folder>"
    $env:PYTHONPATH = "backend"
    python -m app.infrastructure.database.embedded run -- \\
        python experiments/rfc-038-search/measure_search_scale.py

It refuses a database that already has images.
"""

from __future__ import annotations

import argparse
import datetime
import math
import random
import statistics
import sys
import time
import uuid
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from sqlalchemy import text  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

from app.domain.value_objects.embedding_vector import EmbeddingVector  # noqa: E402
from app.infrastructure.persistence.postgres_image_repository import (  # noqa: E402
    PostgresImageRepository,
)
from app.infrastructure.persistence.session import get_db  # noqa: E402

BENCH_DEVICE = uuid.UUID("00000000-0000-0000-0000-000000000038")
DIMENSION = 512
CHUNK = 10_000
QUERIES = 25
ROUNDS = 3
LIMITS = (40, 100)


def unit_vector(generator: random.Random) -> EmbeddingVector:
    values = [generator.gauss(0.0, 1.0) for _ in range(DIMENSION)]
    norm = math.sqrt(sum(value * value for value in values))
    return EmbeddingVector(tuple(value / norm for value in values))


def seed(session: Session, rows: int) -> None:
    already = session.execute(text("SELECT count(*) FROM images")).scalar_one()
    if already:
        raise SystemExit(
            f"this database has {already} images: run against an empty cluster "
            "of its own (EMBEDDED_POSTGRES_DIRECTORY), never the development one"
        )
    began = time.perf_counter()
    session.execute(text("DROP INDEX IF EXISTS ix_images_embedding_hnsw"))
    now = datetime.datetime.now(tz=datetime.UTC)
    session.execute(
        text(
            "INSERT INTO devices (id, volume_identity, volume_kind, label, "
            "first_seen_at, last_seen_at) VALUES (:id, :identity, "
            "'windows-volume-guid', 'HD-BENCH', :now, :now)"
        ),
        {"id": str(BENCH_DEVICE), "identity": "\\\\?\\Volume{bench-038}\\", "now": now},
    )
    # `WHERE n > 0` ties the inner SELECT to the row, so that every row gets
    # its own 512 draws instead of one array computed once.
    statement = text(
        "INSERT INTO images (id, device_id, relative_path, filename, extension, "
        "embedding) "
        "SELECT gen_random_uuid(), :device, 'bench/' || (:offset + n) || '.jpg', "
        "'bench', 'jpg', l2_normalize(CAST(ARRAY("
        "  SELECT random() - 0.5 FROM generate_series(1, 512) WHERE n > 0"
        ") AS vector)) "
        "FROM generate_series(1, :count) AS n"
    )
    for offset in range(0, rows, CHUNK):
        count = min(CHUNK, rows - offset)
        session.execute(
            statement, {"device": str(BENCH_DEVICE), "offset": offset, "count": count}
        )
        session.commit()
        print(f"  {offset + count} rows", flush=True)
    session.execute(text("ANALYZE images"))
    session.commit()
    print(f"seeded {rows} rows in {time.perf_counter() - began:.1f} s", flush=True)


def sizes(session: Session, table: str) -> str:
    row = session.execute(
        text(
            "SELECT pg_relation_size(c.oid), "
            "coalesce(pg_total_relation_size(c.reltoastrelid), 0), "
            "pg_total_relation_size(c.oid) "
            "FROM pg_class c WHERE c.relname = :table"
        ),
        {"table": table},
    ).one()
    heap, toast, total = (value / 2**20 for value in row)
    return f"heap {heap:.0f} MB, TOAST {toast:.0f} MB, total {total:.0f} MB"


def explain(session: Session, query: EmbeddingVector, limit: int) -> None:
    """The shape of `search_statement()` with no filter: the vector is bound
    here as a literal, which the SQLAlchemy type does not render."""
    literal = "[" + ",".join(f"{value:.8f}" for value in query.values) + "]"
    plan = session.execute(
        text(
            "EXPLAIN (ANALYZE, BUFFERS, TIMING OFF) "
            "SELECT id, relative_path, embedding <=> CAST(:query AS vector) "
            "AS distance FROM images WHERE embedding IS NOT NULL "
            "ORDER BY distance, id LIMIT :limit"
        ),
        {"query": literal, "limit": limit},
    ).scalars()
    for line in plan:
        print(f"    {line}")


def measure(session: Session, label: str, queries: list[EmbeddingVector]) -> None:
    repository = PostgresImageRepository(session)
    print(f"\n== {label}", flush=True)
    for limit in LIMITS:
        for round_number in range(1, ROUNDS + 1):
            times = []
            for query in queries:
                began = time.perf_counter()
                hits = repository.search_similar(query, limit)
                times.append((time.perf_counter() - began) * 1000)
                session.rollback()
                assert len(hits) == limit, len(hits)
            ordered = sorted(times)
            p95 = ordered[max(0, math.ceil(0.95 * len(ordered)) - 1)]
            print(
                f"  limit {limit:>3}, round {round_number}: median "
                f"{statistics.median(times):7.0f} ms, p95 {p95:7.0f} ms, "
                f"min {ordered[0]:6.0f}, max {ordered[-1]:6.0f}  "
                f"({len(times)} searches)",
                flush=True,
            )
    print("  EXPLAIN (ANALYZE, BUFFERS) of one search, limit 40:")
    explain(session, queries[0], 40)
    session.rollback()


def make_plain_copy(session: Session) -> None:
    """The same rows in a table whose vector stays in the row, swapped in."""
    began = time.perf_counter()
    session.execute(
        text(
            "CREATE TABLE images_plain "
            "(LIKE images INCLUDING DEFAULTS INCLUDING CONSTRAINTS)"
        )
    )
    session.execute(
        text("ALTER TABLE images_plain ALTER COLUMN embedding SET STORAGE PLAIN")
    )
    session.execute(text("INSERT INTO images_plain SELECT * FROM images"))
    session.execute(text("ALTER TABLE images RENAME TO images_toast"))
    session.execute(text("ALTER TABLE images_plain RENAME TO images"))
    session.commit()
    session.execute(text("ANALYZE images"))
    session.commit()
    print(f"\ncopied to STORAGE PLAIN in {time.perf_counter() - began:.1f} s")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rows", type=int, default=100_000)
    args = parser.parse_args()

    session = next(get_db())
    version = session.execute(text("SHOW server_version")).scalar_one()
    vector = session.execute(
        text("SELECT extversion FROM pg_extension WHERE extname = 'vector'")
    ).scalar_one()
    print(f"PostgreSQL {version}, pgvector {vector}", flush=True)

    seed(session, args.rows)
    print(f"images: {sizes(session, 'images')}")

    generator = random.Random(38)
    queries = [unit_vector(generator) for _ in range(QUERIES)]
    measure(session, f"{args.rows} rows, the vector in TOAST (as the app has it)", queries)

    make_plain_copy(session)
    print(f"images (PLAIN): {sizes(session, 'images')}")
    measure(session, f"{args.rows} rows, the vector in the row (STORAGE PLAIN)", queries)
    session.close()


if __name__ == "__main__":
    main()
